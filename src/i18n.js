// The language of the visitor's browser. It no longer decides the language of the page (the
// address does): it is only used to offer the other language to someone who may prefer it.
export function detectLang() {
  try {
    const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
    const first = String(list[0] || "").toLowerCase();
    return first.startsWith("es") ? "es" : "en";
  } catch (err) {
    return "en";
  }
}

// Replaces {name} marks in a text
export function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
}

// "1 upload" or "3 uploads": picks key_one or key_many by the number
export function countText(t, key, n) {
  return t(n === 1 ? `${key}_one` : `${key}_many`, { n });
}

// t(lang)("key", { name: value })
export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return function t(key, vars) {
    let text = table[key];
    if (text === undefined) text = STRINGS.en[key];
    if (text === undefined) return key;
    if (typeof text !== "string" || !vars) return text;
    return fill(text, vars);
  };
}

export function formatNumber(lang, value, decimals = 0) {
  return new Intl.NumberFormat(LOCALES[lang] || LOCALES.en, {
    minimumFractionDigits: 0,
    maximumFractionDigits: decimals,
  }).format(value);
}

export function formatMoney(lang, value) {
  return `$${formatNumber(lang, Math.round(value))}`;
}
